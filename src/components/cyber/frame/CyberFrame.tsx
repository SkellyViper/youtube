import React from 'react';
import {alpha, cyber, tone as toneOf, type Tone} from '../../../styles/cyber';

const clamp01 = (t: number) => Math.min(1, Math.max(0, t));
const seg = (t: number, a: number, b: number) => clamp01((t - a) / (b - a));

export type CyberFrameProps = {
  /** Top-left corner and size of the content area, in composition px. */
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
  /** Colour role of the frame chrome. Blue = evidence / systems (default). */
  readonly tone?: Tone;
  /**
   * 0 -> 1 builds the chrome: corner brackets land, hairlines draw out from
   * the corners, the spine lights. At 0 nothing is visible.
   */
  readonly build?: number;
  /**
   * 0 -> 1 opens the content: an aperture that grows from the horizontal
   * centre line. Independent of `build` so media can be revealed later.
   */
  readonly open?: number;
  /** Multiplies content brightness (0.25 = dimmed, 1 = normal). */
  readonly brightness?: number;
  /** Whole-frame opacity. */
  readonly opacity?: number;
  /** Perspective tilt in degrees and depth in px (optional hybrid/3D staging). */
  readonly rotateX?: number;
  readonly rotateY?: number;
  readonly rotateZ?: number;
  readonly z?: number;
  /** Uniform scale around the frame centre. */
  readonly scale?: number;
  /** Outer glow strength 0..1. */
  readonly glow?: number;
  /** Small caption under the bottom-left corner (e.g. the source domain). */
  readonly caption?: React.ReactNode;
  /** Secondary caption, right-aligned (e.g. a date). */
  readonly meta?: React.ReactNode;
  /** 0..1 caption visibility. */
  readonly captionOpacity?: number;
  /** Extra chrome drawn above the content but inside the frame (highlights...). */
  readonly overlay?: React.ReactNode;
  readonly children?: React.ReactNode;
};

/**
 * The channel's media frame. Everything that is not generated by the engine
 * (a web page, a paper, a photo, a clip) sits inside one of these, so outside
 * material always looks like it belongs to the same world.
 *
 * Anatomy (deliberately quiet, the content is the point):
 *   - hairline border, 1.25 px, cool and faint;
 *   - four corner brackets standing 10 px off the corners;
 *   - a short lit "spine" on the left edge in the tone colour;
 *   - a soft pool of tone-coloured light under the frame;
 *   - nothing is ever drawn over the content except explicit `overlay`s.
 */
export const CyberFrame: React.FC<CyberFrameProps> = ({
  x,
  y,
  width,
  height,
  tone = 'system',
  build = 1,
  open = 1,
  brightness = 1,
  opacity = 1,
  rotateX = 0,
  rotateY = 0,
  rotateZ = 0,
  z = 0,
  scale = 1,
  glow = 0.5,
  caption,
  meta,
  captionOpacity = 1,
  overlay,
  children,
}) => {
  if (build <= 0.001 || opacity <= 0.001) return null;
  const t = toneOf(tone);
  const corners = seg(build, 0, 0.45);
  const lines = seg(build, 0.2, 0.9);
  const spine = seg(build, 0.55, 1);
  const off = 10;
  const arm = 26 * corners;
  const o = clamp01(open);
  const hasTransform = rotateX !== 0 || rotateY !== 0 || rotateZ !== 0 || z !== 0 || scale !== 1;

  const bracket = (cx: number, cy: number, sx: number, sy: number) => (
    <path
      d={`M${cx} ${cy + sy * arm}V${cy}H${cx + sx * arm}`}
      stroke={t.base}
      strokeWidth={cyber.line.thin}
      fill="none"
      opacity={corners}
    />
  );

  return (
    <div
      style={{
        position: 'absolute',
        left: x,
        top: y,
        width,
        height,
        opacity,
        transformOrigin: '50% 50%',
        transform: hasTransform
          ? `perspective(2400px) translateZ(${z}px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) rotateZ(${rotateZ}deg) scale(${scale})`
          : undefined,
      }}
    >
      {/* Light pooled behind / under the frame. */}
      <div
        style={{
          position: 'absolute',
          inset: -2,
          opacity: lines * glow,
          boxShadow: `0 0 90px ${alpha(t.base, 0.22)}, 0 50px 120px ${alpha(t.deep, 0.35)}`,
        }}
      />
      {/* Content area. */}
      <div
        style={{
          position: 'absolute',
          inset: 0,
          overflow: 'hidden',
          backgroundColor: cyber.color.abyss,
          clipPath: o >= 1 ? undefined : `inset(${(50 * (1 - o)).toFixed(3)}% 0)`,
          opacity: o <= 0 ? 0 : 1,
        }}
      >
        <div style={{position: 'absolute', inset: 0, filter: brightness === 1 ? undefined : `brightness(${brightness})`}}>{children}</div>
        {overlay}
      </div>
      {/* Chrome. */}
      <svg
        width={width + off * 4}
        height={height + off * 4}
        viewBox={`${-off * 2} ${-off * 2} ${width + off * 4} ${height + off * 4}`}
        style={{position: 'absolute', left: -off * 2, top: -off * 2, overflow: 'visible', pointerEvents: 'none'}}
      >
        {/* Hairline border drawing out from the corners. */}
        <g stroke={alpha(t.hot, 0.34)} strokeWidth={cyber.line.hair} fill="none">
          <path d={`M0 0H${(width / 2) * lines}M${width} 0H${width - (width / 2) * lines}`} />
          <path d={`M0 ${height}H${(width / 2) * lines}M${width} ${height}H${width - (width / 2) * lines}`} />
          <path d={`M0 0V${(height / 2) * lines}M0 ${height}V${height - (height / 2) * lines}`} />
          <path d={`M${width} 0V${(height / 2) * lines}M${width} ${height}V${height - (height / 2) * lines}`} />
        </g>
        {/* The aperture's leading edges while the content opens. */}
        {o > 0 && o < 1 ? (
          <g stroke={t.hot} strokeWidth={cyber.line.thin} opacity={0.9}>
            <path d={`M0 ${(height / 2) * (1 - o)}H${width}`} />
            <path d={`M0 ${height - (height / 2) * (1 - o)}H${width}`} />
          </g>
        ) : null}
        {bracket(-off, -off, 1, 1)}
        {bracket(width + off, -off, -1, 1)}
        {bracket(width + off, height + off, -1, -1)}
        {bracket(-off, height + off, 1, -1)}
        {/* Spine. */}
        <path d={`M${-off} ${height * 0.5 - 44 * spine}V${height * 0.5 + 44 * spine}`} stroke={t.base} strokeWidth={cyber.line.medium} opacity={spine} />
        <path d={`M${-off} ${height * 0.5 - 44 * spine}V${height * 0.5 + 44 * spine}`} stroke={t.base} strokeWidth={10} opacity={0.22 * spine} />
      </svg>
      {caption || meta ? (
        <div
          style={{
            position: 'absolute',
            left: 0,
            right: 0,
            top: height + off + 18,
            display: 'flex',
            justifyContent: 'space-between',
            alignItems: 'baseline',
            gap: 32,
            opacity: captionOpacity * spine,
            color: cyber.color.text,
            fontSize: cyber.size.label,
            lineHeight: 1.2,
            ...cyber.labelStyle,
          }}
        >
          <span>{caption}</span>
          <span style={{color: cyber.color.dim}}>{meta}</span>
        </div>
      ) : null}
    </div>
  );
};

/**
 * Emphasis for one region of whatever is inside a frame (or anywhere on
 * screen): the region stays at full brightness, everything else is dimmed,
 * and thin brackets mark its corners. Nothing is drawn on top of the region
 * itself, so text inside it stays perfectly readable.
 *
 * Coordinates are in the px space of the element it is placed in
 * (use it as a CyberFrame `overlay` with content-area coordinates).
 */
export const RegionHighlight: React.FC<{
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
  /** 0..1 */
  readonly progress: number;
  readonly tone?: Tone;
  /** How much the rest is darkened at progress 1 (0..1). */
  readonly dim?: number;
  readonly pad?: number;
}> = ({x, y, width, height, progress, tone = 'system', dim = 0.62, pad = 10}) => {
  if (progress <= 0.001) return null;
  const t = toneOf(tone);
  const p = clamp01(progress);
  const X = x - pad;
  const Y = y - pad;
  const W = width + pad * 2;
  const H = height + pad * 2;
  const arm = Math.min(22, W / 3, H / 3);
  // The brackets close in from slightly outside.
  const spread = (1 - p) * 26;
  return (
    <div style={{position: 'absolute', inset: 0, pointerEvents: 'none'}}>
      {/* Dim everything except the region: a huge box-shadow around a transparent window. */}
      <div
        style={{
          position: 'absolute',
          left: X,
          top: Y,
          width: W,
          height: H,
          boxShadow: `0 0 0 9999px rgba(3, 4, 9, ${(dim * p).toFixed(3)})`,
        }}
      />
      <svg style={{position: 'absolute', inset: 0, width: '100%', height: '100%', overflow: 'visible'}}>
        <g stroke={t.base} strokeWidth={cyber.line.medium} fill="none" opacity={p}>
          <path d={`M${X - spread} ${Y - spread + arm}V${Y - spread}H${X - spread + arm}`} />
          <path d={`M${X + W + spread - arm} ${Y - spread}H${X + W + spread}V${Y - spread + arm}`} />
          <path d={`M${X + W + spread} ${Y + H + spread - arm}V${Y + H + spread}H${X + W + spread - arm}`} />
          <path d={`M${X - spread + arm} ${Y + H + spread}H${X - spread}V${Y + H + spread - arm}`} />
        </g>
        <rect x={X} y={Y} width={W} height={H} fill="none" stroke={alpha(t.hot, 0.35 * p)} strokeWidth={cyber.line.hair} />
      </svg>
    </div>
  );
};
