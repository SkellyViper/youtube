// Style Lab tooling: stills, renders, thumbnails, frame extraction, contact sheet.
//
//   node scripts/lab.mjs stills 03-swarm                 checkpoint + mid-beat frames of one sample (fast, isolated bundle)
//   node scripts/lab.mjs stills 03-swarm --frames=0,90   specific frames
//   node scripts/lab.mjs stills 03-swarm --every=0.5     one frame every 0.5 s
//   node scripts/lab.mjs stills 03-swarm --scale=1 --png full-resolution lossless
//   node scripts/lab.mjs render                          all ten -> out/style-lab/<slug>.mp4 (+ verification)
//   node scripts/lab.mjs render 01-hero 07-source        only these
//   node scripts/lab.mjs thumbs                          gallery thumbnails -> public/lab/thumbs/<slug>.jpg
//   node scripts/lab.mjs frames                          extract key frames from the rendered MP4s -> out/style-lab/frames/
//   node scripts/lab.mjs sheet                           contact sheet from the MP4s -> out/style-lab/contact-sheet.jpg
//   node scripts/lab.mjs check                           analyse the MP4s: black frames, flicker, frozen holds -> out/style-lab/verification.json
//   node scripts/lab.mjs compare                         live presenter vs exported frame at every sample's poster checkpoint (needs `npm run dev`)
//   node scripts/lab.mjs info 03-swarm                   print the beat sheet (frames) of a sample
//
// `stills` / `info` with a single slug bundle only that sample, so a broken
// sample elsewhere never blocks you. WebGL uses ANGLE (GPU) in headless Chrome.
import {execFileSync, spawnSync} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {bundle} from '@remotion/bundler';
import {ensureBrowser, getCompositions, openBrowser, renderMedia, renderStill} from '@remotion/renderer';
import {verifyVideo} from './verify-video.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const command = args[0];
const positional = args.slice(1).filter((a) => !a.startsWith('--'));
const flag = (name) => args.find((a) => a.startsWith(`--${name}=`))?.split('=')[1];
const has = (name) => args.includes(`--${name}`);

const SLUGS = ['01-hero', '02-agent', '03-swarm', '04-network', '05-scan', '06-cloud', '07-source', '08-media', '09-diagram', '10-ending'];
const chromiumOptions = {gl: flag('gl') ?? 'angle'};
const outRoot = path.join(root, 'out', 'style-lab');

const resolveSlugs = () => {
  if (positional.length === 0 || positional.includes('all')) return SLUGS;
  return positional.map((p) => {
    const hit = SLUGS.find((s) => s === p || s.startsWith(`${p}-`) || s.split('-')[1] === p || String(Number(s.slice(0, 2))) === p);
    if (!hit) throw new Error(`Unknown sample "${p}". Known: ${SLUGS.join(', ')}`);
    return hit;
  });
};

/** Bundle either the whole project or a single sample (isolated entry point). */
const makeBundle = async (slugs) => {
  let entryPoint = path.join(root, 'src/remotion/index.ts');
  if (slugs.length === 1 && !has('full')) {
    const slug = slugs[0];
    const dir = path.join(root, '.lab');
    fs.mkdirSync(dir, {recursive: true});
    entryPoint = path.join(dir, `entry-${slug}.tsx`);
    fs.writeFileSync(
      entryPoint,
      `// Generated by scripts/lab.mjs: registers only sample ${slug}.
import React from 'react';
import {Composition, registerRoot} from 'remotion';
import {buildTimeline} from '../src/engine';
import {episode, Sample} from '../src/scenes/style-lab/${slug}';

const t = buildTimeline(episode, 60);
const info = {
  slug: '${slug}',
  title: episode.title,
  durationInFrames: t.durationInFrames,
  checkpoints: [...t.checkpoints],
  posterFrame: t.checkpoints[t.checkpoints.length - 1],
  beats: t.beats.map((b) => ({id: b.id, label: b.label, start: b.start, animEnd: b.animEnd, end: b.end})),
};
const Root = () => (
  <Composition id="lab-${slug}" component={Sample} fps={60} width={1920} height={1080} durationInFrames={t.durationInFrames} defaultProps={{lab: info}} />
);
registerRoot(Root);
`,
    );
  }
  const t0 = Date.now();
  const serveUrl = await bundle({entryPoint, publicDir: path.join(root, 'public')});
  console.log(`[lab] bundled ${path.relative(root, entryPoint)} in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  return serveUrl;
};

const loadCompositions = async (serveUrl, puppeteerInstance) => {
  const comps = await getCompositions(serveUrl, {puppeteerInstance, chromiumOptions});
  return new Map(comps.filter((c) => c.id.startsWith('lab-')).map((c) => [c.id.slice(4), c]));
};

const pad = (n, w = 5) => String(n).padStart(w, '0');

/** Structural similarity of two images (0..1), via ffmpeg's ssim filter. */
const spawnSsim = (a, b) => {
  const r = spawnSync('ffmpeg', ['-v', 'info', '-i', a, '-i', b, '-lavfi', 'ssim', '-f', 'null', '-'], {encoding: 'utf8'});
  const m = String(r.stderr).match(/All:([0-9.]+)/);
  return m ? Number(m[1]) : 0;
};

const printInfo = (slug, comp) => {
  const lab = comp.defaultProps.lab;
  console.log(`\n${slug}: ${comp.durationInFrames} frames = ${(comp.durationInFrames / comp.fps).toFixed(2)}s @ ${comp.fps}fps, ${lab.beats.length} beats`);
  console.log(`  checkpoint 0   frame 0 (initial state)`);
  lab.beats.forEach((b, i) => {
    console.log(`  beat ${String(i + 1).padStart(2)} ${b.id.padEnd(22)} start ${pad(b.start, 4)}  done ${pad(b.animEnd, 4)} (checkpoint ${i + 1})  next ${pad(b.end, 4)}`);
  });
};

const commands = {
  async info() {
    const slugs = resolveSlugs();
    await ensureBrowser();
    const serveUrl = await makeBundle(slugs);
    const comps = await loadCompositions(serveUrl);
    for (const slug of slugs) printInfo(slug, comps.get(slug));
  },

  async stills() {
    const slugs = resolveSlugs();
    await ensureBrowser();
    const serveUrl = await makeBundle(slugs);
    const browser = await openBrowser('chrome', {chromiumOptions});
    const comps = await loadCompositions(serveUrl, browser);
    const scale = Number(flag('scale') ?? 0.5);
    const png = has('png');
    for (const slug of slugs) {
      const comp = comps.get(slug);
      const lab = comp.defaultProps.lab;
      const last = comp.durationInFrames - 1;
      let frames;
      if (flag('frames')) {
        frames = flag('frames').split(',').map((f) => ({frame: Math.min(last, Number(f)), tag: ''}));
      } else if (flag('every')) {
        const step = Math.max(1, Math.round(Number(flag('every')) * comp.fps));
        frames = [];
        for (let f = 0; f <= last; f += step) frames.push({frame: f, tag: ''});
      } else {
        // Default: every checkpoint, plus the middle of every beat's animation.
        frames = [{frame: 0, tag: 'c0'}];
        lab.beats.forEach((b, i) => {
          if (!has('checkpoints')) frames.push({frame: Math.round((b.start + b.animEnd) / 2), tag: `b${i + 1}-mid`});
          frames.push({frame: b.animEnd, tag: `c${i + 1}`});
        });
      }
      const outDir = path.resolve(root, flag('out') ?? path.join('out', 'style-lab', 'stills', slug));
      fs.mkdirSync(outDir, {recursive: true});
      printInfo(slug, comp);
      for (const {frame, tag} of frames) {
        const output = path.join(outDir, `${slug}-f${pad(frame)}${tag ? `-${tag}` : ''}.${png ? 'png' : 'jpg'}`);
        await renderStill({
          composition: comp,
          serveUrl,
          frame,
          output,
          imageFormat: png ? 'png' : 'jpeg',
          ...(png ? {} : {jpegQuality: 90}),
          scale,
          puppeteerInstance: browser,
          chromiumOptions,
          overwrite: true,
        });
        console.log(`[still] ${path.relative(root, output)}`);
      }
    }
    await browser.close({silent: true});
  },

  async thumbs() {
    const slugs = resolveSlugs();
    await ensureBrowser();
    const serveUrl = await makeBundle(SLUGS);
    const browser = await openBrowser('chrome', {chromiumOptions});
    const comps = await loadCompositions(serveUrl, browser);
    const outDir = path.join(root, 'public', 'lab', 'thumbs');
    fs.mkdirSync(outDir, {recursive: true});
    for (const slug of slugs) {
      const comp = comps.get(slug);
      const output = path.join(outDir, `${slug}.jpg`);
      await renderStill({
        composition: comp,
        serveUrl,
        frame: comp.defaultProps.lab.posterFrame,
        output,
        imageFormat: 'jpeg',
        jpegQuality: 86,
        scale: 0.5,
        puppeteerInstance: browser,
        chromiumOptions,
        overwrite: true,
      });
      console.log(`[thumb] ${path.relative(root, output)} (frame ${comp.defaultProps.lab.posterFrame})`);
    }
    await browser.close({silent: true});
  },

  async render() {
    const slugs = resolveSlugs();
    await ensureBrowser();
    const serveUrl = await makeBundle(slugs);
    const comps = await loadCompositions(serveUrl);
    fs.mkdirSync(outRoot, {recursive: true});
    const concurrency = Number(flag('concurrency') ?? Math.max(1, Math.min(8, Math.floor(os.cpus().length / 4))));
    const results = [];
    for (const slug of slugs) {
      const comp = comps.get(slug);
      const output = path.join(outRoot, `${slug}.mp4`);
      const t0 = Date.now();
      console.log(`\n[render] ${slug}: ${comp.durationInFrames} frames (${(comp.durationInFrames / comp.fps).toFixed(2)}s), concurrency ${concurrency}`);
      let lastLog = 0;
      await renderMedia({
        composition: comp,
        serveUrl,
        codec: 'h264',
        outputLocation: output,
        imageFormat: 'png',
        crf: 16,
        pixelFormat: 'yuv420p',
        colorSpace: 'bt709',
        x264Preset: 'slow',
        concurrency,
        chromiumOptions,
        overwrite: true,
        onProgress: ({progress, renderedFrames}) => {
          const now = Date.now();
          if (now - lastLog < 4000 && progress < 1) return;
          lastLog = now;
          process.stdout.write(`[render] ${slug} ${(progress * 100).toFixed(0).padStart(3)}%  (${renderedFrames} frames)\n`);
        },
      });
      console.log(`[render] wrote ${path.relative(root, output)} in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
      const ok = await verifyVideo(output, {width: comp.width, height: comp.height, fps: comp.fps, frames: comp.durationInFrames});
      results.push({slug, ok, seconds: comp.durationInFrames / comp.fps, lab: comp.defaultProps.lab});
    }
    // Remember the beat sheets next to the videos so `frames` / `sheet` work without bundling.
    const manifestFile = path.join(outRoot, 'manifest.json');
    const manifest = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile, 'utf8')) : {};
    for (const r of results) manifest[r.slug] = r.lab;
    fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2));
    console.log('\n[render] summary');
    for (const r of results) console.log(`  ${r.ok ? '✓' : '✗'} ${r.slug}.mp4  ${r.seconds.toFixed(2)}s`);
    if (results.some((r) => !r.ok)) process.exit(1);
  },

  /** Pull first / mid / reveal / final frames out of the actual MP4s. */
  async frames() {
    const slugs = resolveSlugs();
    const manifest = JSON.parse(fs.readFileSync(path.join(outRoot, 'manifest.json'), 'utf8'));
    const scale = flag('scale') ?? '960:-2';
    for (const slug of slugs) {
      const lab = manifest[slug];
      const file = path.join(outRoot, `${slug}.mp4`);
      if (!lab || !fs.existsSync(file)) {
        console.warn(`[frames] skipping ${slug}: not rendered`);
        continue;
      }
      const outDir = path.join(outRoot, 'frames', slug);
      fs.mkdirSync(outDir, {recursive: true});
      const beats = lab.beats;
      const midBeat = beats[Math.floor((beats.length - 1) / 2)];
      const picks = [
        ['1-initial', 0],
        ['2-mid-animation', Math.round((midBeat.start + midBeat.animEnd) / 2)],
        ['3-reveal', lab.posterFrame],
        ['4-final-hold', lab.durationInFrames - 1],
        ...(has('all-checkpoints') ? lab.checkpoints.map((f, i) => [`c${i}`, f]) : []),
      ];
      for (const [name, frame] of picks) {
        const output = path.join(outDir, `${slug}-${name}-f${pad(frame)}.jpg`);
        execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', file, '-vf', `select=eq(n\\,${frame}),scale=${scale}`, '-frames:v', '1', '-q:v', '2', output]);
        console.log(`[frames] ${path.relative(root, output)}`);
      }
    }
  },

  /**
   * Frame-level analysis of the rendered MP4s (decodes every frame with ffmpeg):
   *  - black frames: a failed 3D render or a missing asset shows up as (near) black;
   *  - flicker: luma that jumps up-down-up between consecutive frames;
   *  - holds: between a beat's completed frame and the next beat's first frame the
   *    picture must not move, which is what makes the export match the presenter.
   */
  async check() {
    const slugs = resolveSlugs();
    const manifest = JSON.parse(fs.readFileSync(path.join(outRoot, 'manifest.json'), 'utf8'));
    const report = {};
    let failed = false;
    for (const slug of slugs) {
      const lab = manifest[slug];
      const file = path.join(outRoot, `${slug}.mp4`);
      if (!lab || !fs.existsSync(file)) {
        console.warn(`[check] ${slug}: not rendered`);
        report[slug] = {rendered: false};
        failed = true;
        continue;
      }
      const stats = path.join(os.tmpdir(), `lab-stats-${slug}-${process.pid}.txt`);
      // ffmpeg filter paths need forward slashes and an escaped drive colon.
      const statsArg = stats.split(path.sep).join('/').replace(':', String.fromCharCode(92) + ':');
      execFileSync('ffmpeg', ['-v', 'error', '-i', file, '-vf', `signalstats,metadata=print:file='${statsArg}'`, '-f', 'null', '-'], {stdio: ['ignore', 'ignore', 'pipe']});
      const yavg = [];
      const ydif = [];
      for (const line of fs.readFileSync(stats, 'utf8').split(String.fromCharCode(10))) {
        const a = line.match(/lavfi[.]signalstats[.]YAVG=([0-9.eE+-]+)/);
        if (a) yavg.push(Number(a[1]));
        const d = line.match(/lavfi[.]signalstats[.]YDIF=([0-9.eE+-]+)/);
        if (d) ydif.push(Number(d[1]));
      }
      fs.rmSync(stats, {force: true});
      const n = yavg.length;
      // Video black is 16. A frame of only the void colour sits around 19-20.
      const black = yavg.filter((y) => y < 17.2).length;
      let flicker = 0;
      for (let i = 1; i < n - 1; i++) {
        const a = yavg[i] - yavg[i - 1];
        const b = yavg[i + 1] - yavg[i];
        if (a * b < 0 && Math.abs(a) > 1.5 && Math.abs(b) > 1.5) flicker++;
      }
      // Holds: frames (animEnd, end) of each beat must be static. The first two
      // frames after a beat are skipped: the encoder is still settling there.
      let holdFrames = 0;
      let holdMotion = 0;
      let worstHold = 0;
      for (const b of lab.beats) {
        for (let f = b.animEnd + 3; f < Math.min(b.end, n); f++) {
          holdFrames++;
          worstHold = Math.max(worstHold, ydif[f] ?? 0);
          if ((ydif[f] ?? 0) > 0.35) holdMotion++;
        }
      }
      // Beats: something must actually move while a beat plays.
      const stillBeats = lab.beats
        .filter((b) => {
          let moving = 0;
          for (let f = b.start + 1; f <= Math.min(b.animEnd, n - 1); f++) if ((ydif[f] ?? 0) > 0.05) moving++;
          return moving < (b.animEnd - b.start) * 0.3;
        })
        .map((b) => b.id);
      const result = {
        rendered: true,
        frames: n,
        expectedFrames: lab.durationInFrames,
        seconds: Number((n / 60).toFixed(2)),
        lumaMin: Number(Math.min(...yavg).toFixed(1)),
        lumaMax: Number(Math.max(...yavg).toFixed(1)),
        lumaFinal: Number(yavg[n - 1].toFixed(1)),
        blackFrames: black,
        flickerFrames: flicker,
        holdFrames,
        holdFramesWithMotion: holdMotion,
        worstHoldDiff: Number(worstHold.toFixed(3)),
        beatsWithoutMotion: stillBeats,
      };
      const ok =
        n === lab.durationInFrames &&
        black < n * 0.5 &&
        result.lumaFinal >= 17.2 &&
        flicker === 0 &&
        holdMotion === 0 &&
        stillBeats.length === 0;
      result.ok = ok;
      if (!ok) failed = true;
      report[slug] = result;
      console.log(
        `[check] ${ok ? '✓' : '✗'} ${slug.padEnd(11)} ${String(n).padStart(4)} frames  luma ${String(result.lumaMin).padStart(5)}..${String(result.lumaMax).padEnd(5)} final ${String(result.lumaFinal).padEnd(5)}` +
          `  black ${String(black).padStart(3)}  flicker ${flicker}  holds moving ${holdMotion}/${holdFrames} (max diff ${result.worstHoldDiff})` +
          (stillBeats.length ? `  STILL BEATS: ${stillBeats.join(', ')}` : ''),
      );
    }
    fs.writeFileSync(path.join(outRoot, 'verification.json'), JSON.stringify(report, null, 2));
    console.log(`[check] wrote ${path.relative(root, path.join(outRoot, 'verification.json'))}`);
    if (failed) process.exit(1);
  },

  /**
   * Preview = export, measured. For each sample: screenshot the live presenter
   * (real browser, /style-lab/<slug>#c=N at 1920x1080, so the Player is at
   * scale 1) and compare it with the same frame taken from the rendered MP4.
   * Reports SSIM (1.0 = identical). H.264 compression, the grain and the
   * differences between two Chrome builds cost a little; a wrong state, a
   * missing asset or a timing error costs a lot.
   *   --url=http://localhost:5173   where the app is running (npm run dev or npm run present)
   */
  async compare() {
    const slugs = resolveSlugs();
    const {chromium} = await import('@playwright/test');
    const manifest = JSON.parse(fs.readFileSync(path.join(outRoot, 'manifest.json'), 'utf8'));
    const base = flag('url') ?? 'http://localhost:5173';
    const outDir = path.join(outRoot, 'compare');
    fs.mkdirSync(outDir, {recursive: true});
    const browser = await chromium.launch({args: ['--enable-gpu', '--ignore-gpu-blocklist', '--use-angle=d3d11']});
    const page = await browser.newPage({viewport: {width: 1920, height: 1080}, deviceScaleFactor: 1});
    const report = {};
    let failed = false;
    for (const slug of slugs) {
      const lab = manifest[slug];
      const video = path.join(outRoot, `${slug}.mp4`);
      if (!lab || !fs.existsSync(video)) {
        console.warn(`[compare] ${slug}: not rendered`);
        continue;
      }
      const checkpoint = Math.max(0, lab.checkpoints.indexOf(lab.posterFrame));
      const live = path.join(outDir, `${slug}-c${checkpoint}-live.png`);
      const exported = path.join(outDir, `${slug}-c${checkpoint}-export.png`);
      await page.goto(`${base}/style-lab/${slug}#c=${checkpoint}`);
      await page.waitForFunction(
        (c) => window.__presenter && window.__presenter.state.status === 'holding' && window.__presenter.state.checkpoint === c && window.__presenter.frame >= 0,
        checkpoint,
        {timeout: 30000},
      );
      const frame = await page.evaluate(() => window.__presenter.frame);
      // Let media settle and the viewer chrome fade out (it hides after 1.5 s without mouse movement).
      await page.waitForTimeout(3000);
      await page.screenshot({path: live});
      execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', video, '-vf', `select=eq(n${String.fromCharCode(92)},${lab.posterFrame})`, '-frames:v', '1', exported]);
      const ssim = spawnSsim(live, exported);
      const sameFrame = frame === lab.posterFrame;
      const ok = sameFrame && ssim >= 0.93;
      if (!ok) failed = true;
      report[slug] = {checkpoint, liveFrame: frame, exportFrame: lab.posterFrame, ssim: Number(ssim.toFixed(4)), ok};
      console.log(`[compare] ${ok ? '✓' : '✗'} ${slug.padEnd(11)} checkpoint ${checkpoint}  live frame ${frame} / export frame ${lab.posterFrame}  SSIM ${ssim.toFixed(4)}`);
    }
    await browser.close();
    fs.writeFileSync(path.join(outRoot, 'compare.json'), JSON.stringify(report, null, 2));
    console.log(`[compare] images in ${path.relative(root, outDir)}, report in ${path.relative(root, path.join(outRoot, 'compare.json'))}`);
    if (failed) process.exit(1);
  },

  /** One image with all ten samples: poster frame of each, from the MP4s. */
  async sheet() {
    const manifest = JSON.parse(fs.readFileSync(path.join(outRoot, 'manifest.json'), 'utf8'));
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'lab-sheet-'));
    const tiles = [];
    for (const slug of SLUGS) {
      const lab = manifest[slug];
      const file = path.join(outRoot, `${slug}.mp4`);
      if (!lab || !fs.existsSync(file)) {
        console.warn(`[sheet] ${slug} not rendered; skipping`);
        continue;
      }
      const tile = path.join(tmp, `${slug}.png`);
      execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', file, '-vf', `select=eq(n\\,${lab.posterFrame}),scale=768:432`, '-frames:v', '1', tile]);
      tiles.push(tile);
    }
    if (tiles.length === 0) throw new Error('Nothing rendered yet. Run: node scripts/lab.mjs render');
    const cols = 5;
    const rows = Math.ceil(tiles.length / cols);
    const output = path.join(outRoot, 'contact-sheet.jpg');
    const inputs = tiles.flatMap((t) => ['-i', t]);
    const layout = tiles.map((_, i) => `${(i % cols) * 776}_${Math.floor(i / cols) * 440}`).join('|');
    const filter = `xstack=inputs=${tiles.length}:layout=${layout}:fill=0x04050A,pad=${cols * 776 + 8}:${rows * 440 + 8}:8:8:0x04050A`;
    execFileSync('ffmpeg', ['-v', 'error', '-y', ...inputs, '-filter_complex', filter, '-frames:v', '1', '-q:v', '2', output]);
    fs.rmSync(tmp, {recursive: true, force: true});
    console.log(`[sheet] ${path.relative(root, output)} (${tiles.length} samples, ${cols}x${rows})`);
  },
};

if (!commands[command]) {
  console.log('Usage: node scripts/lab.mjs <stills|render|thumbs|frames|sheet|check|compare|info> [slug ...] [options]\nSee the header of scripts/lab.mjs for examples.');
  process.exit(command ? 1 : 0);
}
await commands[command]();
process.exit(0);
